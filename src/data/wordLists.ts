export const generateText = (
  wordCount: number = 30,
  language: Language = "english",
  mode: string = "words",
  includePunctuation: boolean = false,
  includeNumbers: boolean = false
): string => {
  if (mode === "zen") {
    // Generate a long stream for zen mode
    const zenWords = wordCount > 500 ? wordCount : 1000;
    return generateText(zenWords, language, "words", false, false);
  }

  if (mode === "quote") {
    const quote = typingQuotes[Math.floor(Math.random() * typingQuotes.length)];
    return quote;
  }

  if (mode === "characters") {
    const wordList = wordLists[language] || commonWordsEnglish;
    let result = "";
    while (result.length < wordCount) {
      const randomIndex = Math.floor(Math.random() * wordList.length);
      const word = wordList[randomIndex];
      if (result.length + word.length + 1 <= wordCount) {
        result += (result ? " " : "") + word;
      } else {
        const remaining = wordCount - result.length - 1;
        if (remaining > 0) {
          result += " " + word.slice(0, remaining);
        }
        break;
      }
    }
    return result;
  }

  if (mode === "numbers") {
    const numbers: string[] = [];
    for (let i = 0; i < wordCount; i++) {
      const numLength = Math.floor(Math.random() * 4) + 1;
      let num = "";
      for (let j = 0; j < numLength; j++) {
        num += Math.floor(Math.random() * 10);
      }
      numbers.push(num);
    }
    return numbers.join(" ");
  }

  if (mode === "code") {
    const snippets: string[] = [];
    const count = Math.min(10, Math.ceil(wordCount / 5));
    for (let i = 0; i < count; i++) {
      const randomIndex = Math.floor(Math.random() * codeSnippets.length);
      snippets.push(codeSnippets[randomIndex]);
    }
    return snippets.join(" ");
  }

  const wordList = wordLists[language] || commonWordsEnglish;
  const words: string[] = [];

  for (let i = 0; i < wordCount; i++) {
    const randomIndex = Math.floor(Math.random() * wordList.length);
    let word = wordList[randomIndex];

    if (includePunctuation || mode === "punctuation") {
      const shouldAdd = Math.random() > 0.8;
      if (shouldAdd) {
        const mark = punctuationMarks[Math.floor(Math.random() * punctuationMarks.length)];
        const position = Math.random() > 0.5 ? "end" : "start";
        if (position === "end") word += mark;
        else word = mark + (word.charAt(0).toLowerCase() + word.slice(1));
      }
    }

    if (includeNumbers && Math.random() > 0.9) {
      word += Math.floor(Math.random() * 100);
    }

    words.push(word);
  }

  const result = words.join(" ");

  if (mode === "sentences" || mode === "paragraphs") {
    const sentences = result.split(" ");
    let formatted = "";
    for (let i = 0; i < sentences.length; i++) {
      let word = sentences[i];
      if (i === 0 || i % 10 === 0) {
        word = word.charAt(0).toUpperCase() + word.slice(1);
      }
      if (i > 0 && i % 10 === 9) {
        word += ".";
      }
      formatted += word + (i < sentences.length - 1 ? " " : "");
    }
    if (!formatted.endsWith(".")) formatted += ".";
    return formatted;
  }

  return result;
};
